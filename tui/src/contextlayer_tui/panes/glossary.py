class GlossaryPane(Pane):
    columns = ("Term", "Where you see it")
    empty_text = "No terms."

    async def load(self) -> None:
        self.fill([(term, {"term": term, "area": area, "meaning": meaning, "why": why},
                    (f"[bold]{term}[/]", area))
                   for term, area, meaning, why in TERMS])

    def describe(self, item: dict[str, Any]) -> RenderableType:
        return Group(
            Text.from_markup(f"[bold]{item['term']}[/]   [{DIM}]{item['area']}[/]"),
            Text(),
            Text(item["meaning"]),
            Text(),
            Text.from_markup("[bold]Why it matters[/]"),
            Text(item["why"]),
        )
